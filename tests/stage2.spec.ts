import { test, expect } from '@playwright/test'
import {loginAs,resetDemo} from './helpers/auth'
test.beforeEach(async({page})=>{await loginAs(page);await resetDemo(page)})

test('scenario engine survives reload, keeps role context, and requires explicit reset confirmation', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Kontrol demo', exact: true }).click()
  const panel = page.getByRole('dialog', { name: 'Kontrol simulasi' })
  await panel.getByRole('button', { name: 'Buat order sintetis' }).click()
  await panel.getByRole('button', { name: 'Jalankan callback pembayaran' }).click()
  await panel.getByRole('button', { name: 'Terbitkan / ulangi voucher' }).click()
  await expect(panel.getByTestId('voucher-status')).toHaveText('unused')
  await expect(panel.getByTestId('voucher-expiry')).toHaveText('Belum dimulai')
  await panel.getByRole('button', { name: 'Login mock', exact: true }).click()
  await expect(panel.getByTestId('voucher-status')).toHaveText('active')
  const expiry = await panel.getByTestId('voucher-expiry').textContent()
  await panel.getByRole('button', { name: '+1 jam', exact: true }).click()
  await expect(panel.getByTestId('voucher-expiry')).toHaveText(expiry!)
  await panel.getByLabel('Perangkat mock').selectOption('device-demo-2')
  await panel.getByRole('button', { name: 'Login mock', exact: true }).click()
  await expect(panel.getByRole('status')).toContainText('perangkat pertama')
  const orderId = await panel.getByLabel('Order sintetis').inputValue()
  await page.reload()
  await page.getByRole('button', { name: 'Kontrol demo', exact: true }).click()
  await panel.getByLabel('Order sintetis').selectOption(orderId)
  await expect(panel.getByTestId('voucher-expiry')).toHaveText(expiry!)
  await expect(panel.getByLabel('Perangkat mock')).toHaveValue('device-demo-2')
  await panel.getByRole('button', { name: 'Reset data demo', exact: true }).click()
  await panel.getByRole('button', { name: 'Batal reset', exact: true }).click()
  await expect(panel.getByLabel('Order sintetis')).toHaveValue(orderId)
  await page.evaluate(() => localStorage.setItem('other-app', 'keep'))
  await panel.getByRole('button', { name: 'Reset data demo', exact: true }).click()
  await panel.getByRole('button', { name: 'Ya, reset data sintetis', exact: true }).click()
  await expect(panel.getByLabel('Order sintetis').locator(`option[value="${orderId}"]`)).toHaveCount(0)
  expect(await page.evaluate(() => localStorage.getItem('other-app'))).toBe('keep')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Kontrol demo', exact: true })).toBeFocused()
})

