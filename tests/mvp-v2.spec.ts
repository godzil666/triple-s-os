test('deterministic QR camera decode fills a code and still requires server credential validation',async({page})=>{
  await loginAs(page);await resetDemo(page)
  const state=await(await page.request.get('/api/state')).json()
  const voucher=state.vouchers.find((v:{batchId:string|null;partnerId:string;credential?:{type:string}})=>v.batchId&&v.partnerId==='demo-cisaat'&&v.credential?.type!=='username_password')
  await page.addInitScript((decoded:string)=>{
    Object.defineProperty(window,'BarcodeDetector',{configurable:true,value:class{detect(){return Promise.resolve([{rawValue:decoded}])}}})
    Object.defineProperty(navigator,'mediaDevices',{configurable:true,value:{getUserMedia:()=>Promise.resolve(new MediaStream())}})
    HTMLMediaElement.prototype.play=async function(){}
    Object.defineProperty(HTMLMediaElement.prototype,'readyState',{configurable:true,get:()=>4})
  },voucher.code)
  await page.goto('/wifi/hotspot/hotspot-site-demo-cisaat/login')
  await page.getByRole('button',{name:'Scan QR voucher'}).click()
  await expect(page.getByLabel('Kode voucher')).toHaveValue(voucher.code)
  await page.getByRole('button',{name:'Masuk dengan voucher'}).click()
  await expect(page.locator('.hotspot-status')).toContainText('Sesi simulasi aktif')
})

test('camera permission failure keeps manual entry available and rejects an invalid code',async({page})=>{
  await page.addInitScript(()=>{
    Object.defineProperty(window,'BarcodeDetector',{configurable:true,value:class{detect(){return Promise.resolve([{rawValue:'https://invalid.example/voucher'}])}}})
    Object.defineProperty(navigator,'mediaDevices',{configurable:true,value:{getUserMedia:()=>Promise.reject(new DOMException('Denied','NotAllowedError'))}})
  })
  await page.goto('/wifi/hotspot/hotspot-site-demo-cisaat/login')
  await page.getByRole('button',{name:'Scan QR voucher'}).click()
  await expect(page.getByRole('status').filter({hasText:'Izin kamera ditolak'})).toContainText('Izin kamera ditolak')
  await expect(page.getByLabel('Kode voucher')).toBeVisible()
  await page.getByLabel('Kode voucher').fill('BUKAN-VOUCHER')
  await page.getByRole('button',{name:'Masuk dengan voucher'}).click()
  await expect(page.getByRole('alert')).toContainText('tidak dikenali')
})

